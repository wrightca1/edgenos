#define NOPS (sizeof(OPS)/sizeof(OPS[0]))
static void snap(const char*t){uint32_t hi=rd(0xE383Fu);
 fprintf(stderr,"[linkup] %-12s PORT_STATUS=0x%04x TxRdy/RxRdy=%u/%u PIN=0x%x RXCFG=%08x TXCFG=%08x\n",
   t,rd(0xE3800u),(hi>>5)&1u,(hi>>6)&1u,rd(PIN),rd(0xE3839u),rd(0xE383Au)); fflush(stderr);}
int main(int argc,char**argv){
 if(argc<2){fprintf(stderr,"usage: %s <BDF> [pace_us]\n",argv[0]);return 2;}
 if(argc>2) DLY=(unsigned)atoi(argv[2]);
 char p[256]; snprintf(p,sizeof p,"/sys/bus/pci/devices/%s/resource0",argv[1]);
 int fd=open(p,O_RDWR|O_SYNC); if(fd<0){perror("open");return 1;}
 M=mmap(NULL,32u*1024*1024,PROT_READ|PROT_WRITE,MAP_SHARED,fd,0);
 if(M==MAP_FAILED){perror("mmap");return 1;}
 setvbuf(stderr,NULL,_IONBF,0);
 if(rd(PIN)!=0x208u){fprintf(stderr,"[linkup] chip not alive (PIN=0x%08x) -- ABORT\n",rd(PIN));return 1;}
 fprintf(stderr,"[linkup] replaying %u ops (pace %uus)\n",(unsigned)NOPS,DLY);
 snap("before");
 for(unsigned i=0;i<NOPS;i++){
   if(OPS[i].k==0) wr(OPS[i].a,OPS[i].v);
   else{int rc=sbus(OPS[i].a,OPS[i].v);
     if(rc<0){fprintf(stderr,"[linkup] SBus fail rc=%d at op %u cmd=0x%08x -- ABORT\n",rc,i,OPS[i].a);return 3;}}
   if((i%25)==24 && rd(PIN)==0xffffffffu){
     fprintf(stderr,"[linkup] OFF-BUS after op %u (0x%05x <- 0x%08x) -- ABORT\n",i,OPS[i].a,OPS[i].v);return 4;}
   if((i%100)==99){char b[24];snprintf(b,sizeof b,"op %u",i+1);snap(b);}
 }
 snap("after");
 for(int s=0;s<4;s++){sleep(2);snap("settle");}
 uint32_t ps=rd(0xE3800u),hi=rd(0xE383Fu);
 int up=((ps>>6)&1)&&((ps>>7)&1)&&((hi>>5)&1)&&((hi>>6)&1);
 fprintf(stderr,"[linkup] === %s (PORT_STATUS=0x%04x pcsRx=0x%x) ===\n",
   up?"LINK UP":"no link",ps,rd(0xE3826u));
 return up?0:2;}
